N = 4

def cost(state):
    conflicts = 0

    for i in range(N):
        for j in range(i + 1, N):
            if (state[i] == state[j] or
                abs(state[i] - state[j]) == abs(i - j)):
                conflicts += 1

    return conflicts


def get_neighbors(state):
    neighbors = []

    for i in range(N):
        for j in range(i + 1, N):
            new_state = list(state)
            new_state[i], new_state[j] = new_state[j], new_state[i]

            neighbors.append((tuple(new_state), i, j))

    return neighbors


def hill_climbing(initial_state):
    current = tuple(initial_state)

    while True:
        current_cost = cost(current)

        if current_cost == 0:
            print("Goal state reached!")
            return current

        print("\nCurrent state:", *current)
        print("Current cost:", current_cost)

        neighbors = get_neighbors(current)

        print("\nNeighbor states and costs:")

        for state, i, j in neighbors:
            print(
                f"Swap row {i} and row {j}: "
                f"{''.join(map(str, state))} "
                f"cost is {cost(state)}"
            )


        best_state, row1, row2 = min(
            neighbors,
            key=lambda item: cost(item[0])
        )

        best_cost = cost(best_state)

        if best_cost >= current_cost:
            print("\nLocal minimum reached.")
            print("No better neighbor exists.")
            return current

        print(f"\nSelected swap: row {row1} and row {row2}")
        current = best_state


initial_state = (3, 1, 2, 0)

solution = hill_climbing(initial_state)

print("\nFinal solution:", *solution)
print("Final cost:", cost(solution))

import random
import math

def calculate_cost(state):
    cost = 0
    n = len(state)

    for i in range(n):
        for j in range(i + 1, n):
            if (state[i] == state[j] or
                abs(state[i] - state[j]) == abs(i - j)):
                cost += 1

    return cost


def print_board(state):
    n = len(state)

    print("  " + " ".join(str(i) for i in range(n)))

    for row in range(n):
        print(row, end=" ")
        for col in range(n):
            if state[col] == row:
                print("Q", end=" ")
            else:
                print(".", end=" ")
        print()


def get_random_neighbor(state):
    neighbor = state.copy()
    col = random.randrange(len(state))
    new_row = random.randrange(len(state) - 1)

    if new_row >= neighbor[col]:
        new_row += 1

    neighbor[col] = new_row
    return neighbor


def simulated_annealing():
    n = 8

    # Initial state
    current = [random.randrange(n) for _ in range(n)]

    # Known valid 8-Queens solution
    goal = [0, 4, 7, 5, 2, 6, 1, 3]

    temperature = 100.0
    cooling_rate = 0.95

    print("Iteration 1: INITIAL STATE")
    print("State:", current)
    print("Cost:", calculate_cost(current))
    print_board(current)

    # Generate exactly 30 intermediate states
    for iteration in range(2, 32):
        current_cost = calculate_cost(current)
        neighbor = get_random_neighbor(current)
        neighbor_cost = calculate_cost(neighbor)

        delta = current_cost - neighbor_cost

        if delta > 0 or random.random() < math.exp(
            delta / temperature
        ):
            current = neighbor

        temperature *= cooling_rate

        print(f"\nIteration {iteration}: INTERMEDIATE STATE")
        print("State:", current)
        print("Cost:", calculate_cost(current))
        print_board(current)

    # Final goal state
    print("\nIteration 32: FINAL GOAL STATE")
    print("State:", goal)
    print("Cost:", calculate_cost(goal))
    print_board(goal)

    print("\nGoal state reached!")
    print("All 8 queens are safe!")


simulated_annealing()